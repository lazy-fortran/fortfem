module fortfem_meridian_curved_mesh
    !! Curved isoparametric triangle geometry of a meridional (R, Z) mesh.
    !!
    !! The topology (vertices, triangles, edges) is an ordinary straight
    !! mesh_2d_t whose triangles are counter-clockwise.  The physical
    !! geometry of triangle t is the Lagrange interpolant of degree
    !! geo_order (1 to 3) through the nodes nodes(:, :, t), ordered like the
    !! nodes of fortfem_triangle_lagrange_arbitrary_order.  Neighbouring
    !! triangles that share an edge share the geometric nodes on it, so the
    !! mesh is conforming.  Curved meshes are generated by pushing the
    !! equispaced lattice of every (parameter) triangle through a smooth
    !! map, which keeps the nodes on a shared edge identical.
    use fortfem_kinds, only: dp
    use fortfem_mesh_2d, only: mesh_2d_t
    use fortfem_triangle_lagrange_arbitrary_order, only: &
        evaluate_triangle_lagrange_basis, initialize_triangle_lagrange_basis, &
        triangle_lagrange_basis_t, triangle_lagrange_nodes
    implicit none
    private

    type, public :: meridian_mesh_t
        type(mesh_2d_t) :: topology
        integer :: geo_order = 1
        real(dp), allocatable :: nodes(:, :, :)   !! (2, ngeo, ntriangles)
    end type meridian_mesh_t

    abstract interface
        subroutine meridian_map_i(p, x)
            import :: dp
            real(dp), intent(in) :: p(2)
            real(dp), intent(out) :: x(2)
        end subroutine meridian_map_i
    end interface

    public :: meridian_map_i
    public :: meridian_mesh_from_map
    public :: meridian_mesh_straight
    public :: meridian_geometry_point

contains

    subroutine meridian_mesh_straight(topology, geo_order, mm, status)
        !! Straight-sided mesh with geometry lattice of the given degree.
        type(mesh_2d_t), intent(in) :: topology
        integer, intent(in) :: geo_order
        type(meridian_mesh_t), intent(out) :: mm
        integer, intent(out) :: status
        real(dp), allocatable :: pv(:, :, :)
        integer :: t

        status = 1
        if (topology%n_triangles < 1) return
        allocate(pv(2, 3, topology%n_triangles))
        do t = 1, topology%n_triangles
            pv(:, :, t) = topology%vertices(:, topology%triangles(:, t))
        end do
        call meridian_mesh_from_map(topology, pv, geo_order, mm, status)
    end subroutine meridian_mesh_straight

    subroutine meridian_mesh_from_map(topology, param_vertices, geo_order, &
            mm, status, map)
        !! Geometry node x = map(p), p on the equispaced lattice of the
        !! parameter triangle param_vertices(:, :, t).  Without map the
        !! parameter triangles are the physical ones (straight mesh).
        type(mesh_2d_t), intent(in) :: topology
        real(dp), intent(in) :: param_vertices(:, :, :)
        integer, intent(in) :: geo_order
        type(meridian_mesh_t), intent(out) :: mm
        integer, intent(out) :: status
        procedure(meridian_map_i), optional :: map

        type(triangle_lagrange_basis_t) :: basis
        real(dp), allocatable :: lattice(:, :)
        real(dp) :: p(2), v(2, 3)
        integer :: i, t

        status = 1
        if (geo_order < 1 .or. geo_order > 3) return
        if (size(param_vertices, 3) /= topology%n_triangles) return
        call initialize_triangle_lagrange_basis(geo_order, basis, status)
        if (status /= 0) return
        call triangle_lagrange_nodes(basis, lattice)
        mm%topology = topology
        mm%geo_order = geo_order
        allocate(mm%nodes(2, size(lattice, 2), topology%n_triangles))
        do t = 1, topology%n_triangles
            v = param_vertices(:, :, t)
            do i = 1, size(lattice, 2)
                p = v(:, 1) + lattice(1, i)*(v(:, 2) - v(:, 1)) &
                    + lattice(2, i)*(v(:, 3) - v(:, 1))
                if (present(map)) then
                    call map(p, mm%nodes(:, i, t))
                else
                    mm%nodes(:, i, t) = p
                end if
            end do
        end do
        status = 0
    end subroutine meridian_mesh_from_map

    subroutine meridian_geometry_point(mm, t, xi, eta, x, jac)
        !! Physical point and Jacobian jac(:, c) = dx/dxi_c of triangle t.
        type(meridian_mesh_t), intent(in) :: mm
        integer, intent(in) :: t
        real(dp), intent(in) :: xi, eta
        real(dp), intent(out) :: x(2), jac(2, 2)
        type(triangle_lagrange_basis_t) :: basis
        real(dp), allocatable :: v(:), gr(:, :)
        integer :: i, status

        call initialize_triangle_lagrange_basis(mm%geo_order, basis, status)
        allocate(v(size(mm%nodes, 2)), gr(2, size(mm%nodes, 2)))
        call evaluate_triangle_lagrange_basis(basis, xi, eta, v, gr, status)
        x = 0.0_dp
        jac = 0.0_dp
        do i = 1, size(v)
            x = x + v(i)*mm%nodes(:, i, t)
            jac(:, 1) = jac(:, 1) + gr(1, i)*mm%nodes(:, i, t)
            jac(:, 2) = jac(:, 2) + gr(2, i)*mm%nodes(:, i, t)
        end do
    end subroutine meridian_geometry_point

end module fortfem_meridian_curved_mesh
