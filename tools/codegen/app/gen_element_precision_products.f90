program gen_element_precision_products
    use fortsym_arena, only: arena_t
    use fortsym_expr, only: expr_t, sym, num, abs, operator(+), &
                            operator(-), operator(*), operator(/), operator(**)
    use fortsym_engine, only: engine_result_t
    use fortsym_engine_native, only: make_native_engine, native_engine_t
    use fortsym_diff, only: diff
    use fortsym_subs, only: subs_many
    use fortsym_kernel, only: emit_kernel, kernel_spec_t, &
                              PRECISION_REAL64, PRECISION_REAL32
    use fortsym_kernel_ir, only: kernel_ir_t, lower_kernel_ir
    use fortsym_kernel_emit, only: kernel_emit_spec_t, emit_cuda_device_ir
    use fortsym_string, only: str, chars, str_t
    use fortfem_codegen_triangle_basis, only: triangle_scalar_bases
    use fortfem_codegen_provenance, only: generated_path, fortsym_revision
    implicit none
    type(arena_t), target :: arena
    type(native_engine_t) :: engine
    type(expr_t) :: a, b, c, d, k, m, x, y, det, l(3), basis(6)
    type(expr_t) :: gx(3), gy(3), cell(9), factors(5), jets(36), v(2)
    type(expr_t) :: qx(3), qy(3), w, integral
    type(kernel_spec_t) :: spec
    type(kernel_emit_spec_t) :: cuda_spec
    type(kernel_ir_t) :: ir
    type(str_t) :: names(9)
    character(:), allocatable :: suffix, code, message
    character(2) :: digit, digit2
    integer :: precision, unit, cuda_unit, i, j, n, q
    logical :: ok

    call arena%init()
    engine = make_native_engine(arena)
    a = sym(arena, 'a'); b = sym(arena, 'b'); c = sym(arena, 'c'); d = sym(arena, 'd')
    k = sym(arena, 'diffusion'); m = sym(arena, 'reaction')
    x = sym(arena, 'xi'); y = sym(arena, 'eta')
    v = [sym(arena, 'vx'), sym(arena, 'vy')]
    det = a*d - b*c
    call triangle_scalar_bases(x, y, l, basis)
    do i = 1, 3
        gx(i) = (d*diff(l(i), x) - b*diff(l(i), y))/det
        gy(i) = (-c*diff(l(i), x) + a*diff(l(i), y))/det
    end do
    qx = [num(arena, 1)/6, num(arena, 2)/3, num(arena, 1)/6]
    qy = [num(arena, 1)/6, num(arena, 1)/6, num(arena, 2)/3]
    w = num(arena, 1)/6
    n = 0
    do j = 1, 3
        do i = 1, 3
            n = n + 1
            integral = num(arena, 0)
            do q = 1, 3
                integral = integral + w*subs_many(l(i)*l(j), [x, y], [qx(q), qy(q)])
            end do
            cell(n) = abs(det)*(k*(gx(i)*gx(j) + gy(i)*gy(j))/2 + m*integral)
            write (digit, '(i0)') i; write (digit2, '(i0)') j
            names(n) = str('k'//trim(digit)//trim(digit2))
        end do
    end do
    factors = [det, (d*v(1) - b*v(2))/det, (-c*v(1) + a*v(2))/det, &
               (a*v(1) + c*v(2))/det, (b*v(1) + d*v(2))/det]
    do i = 1, 6
        n = 6*(i - 1)
        jets(n + 1:n + 6) = [basis(i), diff(basis(i), x), diff(basis(i), y), &
                             diff(diff(basis(i), x), x), diff(diff(basis(i), x), y), &
                             diff(diff(basis(i), y), y)]
    end do
    call simplify(cell)
    call simplify(factors)
    call simplify(jets)
    open (newunit=unit, file=generated_path( &
          'fortfem_element_precision_products.f90'), status='replace')
    open (newunit=cuda_unit, file=generated_path( &
          'fortfem_element_precision_products.cuh'), status='replace')
 write (cuda_unit, '(a)') '// Generated by gen_element_precision_products; do not edit.'
    write (cuda_unit, '(a)') '// '//fortsym_revision()
    write (cuda_unit, '(a)') '#pragma once'
    write (cuda_unit, '(a)') '#include <math.h>'
    do precision = 1, 2
        if (precision == 1) then
            suffix = 'fp64'
        else
            suffix = 'fp32'
        end if
        call initialize('p1_cell')
        spec%args = [str('a'), str('b'), str('c'), str('d'), &
                     str('diffusion'), str('reaction')]
        spec%outputs = names
        spec%elemental_procedure = .true.
        code = chars(emit_kernel(cell, spec))
        write (unit, '(a)') code(:len(code) - 1)
        call emit_cuda(cell)
        call initialize('triangle_measure')
        spec%args = [str('a'), str('b'), str('c'), str('d')]
        spec%outputs = [str('det'), str('scale')]
        spec%elemental_procedure = .true.
        code = chars(emit_kernel([det, a*a + b*b + c*c + d*d], spec))
        write (unit, '(a)') code(:len(code) - 1)
        call emit_cuda([det, a*a + b*b + c*c + d*d])
        call initialize('triangle_factors')
        spec%args = [str('a'), str('b'), str('c'), str('d'), str('vx'), str('vy')]
        spec%outputs = [str('det'), str('covx'), str('covy'), str('contrax'), &
                        str('contray')]
        spec%elemental_procedure = .true.
        code = chars(emit_kernel(factors, spec))
        write (unit, '(a)') code(:len(code) - 1)
        call initialize('p2_jet')
        spec%args = [str('xi'), str('eta')]
        spec%outputs = [str('jet')]; spec%output_shapes = [str('(6,6)')]
        allocate (spec%output_references(36))
        do i = 1, 6
            do j = 1, 6
                write (digit, '(i0)') i; write (digit2, '(i0)') j
                spec%output_references(6*(i - 1) + j) = &
                    str('jet('//trim(digit2)//','//trim(digit)//')')
            end do
        end do
        code = chars(emit_kernel(jets, spec))
        write (unit, '(a)') code(:len(code) - 1)
    end do
    close (unit); close (cuda_unit)
contains
    subroutine emit_cuda(roots)
        type(expr_t), intent(in) :: roots(:)
        ! Scalar spelling and operation lowering belong to FortSym.
        call lower_kernel_ir(roots, ir, ok, message)
        if (.not. ok) error stop 'element CUDA lowering failed'
        cuda_spec = kernel_emit_spec_t()
        cuda_spec%name = spec%name
        cuda_spec%args = spec%args; cuda_spec%outputs = spec%outputs
        cuda_spec%precision = spec%precision
        cuda_spec%generator = spec%generator
        cuda_spec%generator_revision = spec%generator_revision
        cuda_spec%regenerate_command = spec%regenerate_command
        code = chars(emit_cuda_device_ir(ir, cuda_spec, ok, message))
        if (.not. ok) error stop 'element CUDA emission failed'
        write (cuda_unit, '(a)') code(:len(code) - 1)
    end subroutine emit_cuda

    subroutine simplify(roots)
        type(expr_t), intent(inout) :: roots(:)
        type(engine_result_t) :: result
        integer :: index
        do index = 1, size(roots)
            result = engine%simplify(roots(index))
            if (.not. result%ok) error stop 'element simplification failed'
            roots(index) = result%value
        end do
    end subroutine simplify

    subroutine initialize(family)
        character(*), intent(in) :: family
        spec = kernel_spec_t()
        spec%name = str('generated_'//family//'_'//suffix)
        spec%module_name = str('fortfem_generated_'//family//'_'//suffix)
        spec%generator = str('gen_element_precision_products')
        spec%generator_revision = str(fortsym_revision())
        spec%regenerate_command = str('cd tools/codegen && ./generate.sh')
        spec%pure_procedure = .true.
        if (precision == 1) then
            spec%precision = PRECISION_REAL64
        else
            spec%precision = PRECISION_REAL32
        end if
    end subroutine initialize
end program gen_element_precision_products
